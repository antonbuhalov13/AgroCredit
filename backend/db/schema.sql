-- Fresh local test database for the current Express and analytics modules.
BEGIN;

CREATE TABLE professions (
   id INTEGER PRIMARY KEY,
   name TEXT NOT NULL UNIQUE,
   is_agricultural BOOLEAN NOT NULL
);

CREATE TABLE company_industries (
   id INTEGER PRIMARY KEY,
   name TEXT NOT NULL UNIQUE,
   is_agricultural BOOLEAN NOT NULL
);

CREATE TABLE applications (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100001) PRIMARY KEY,
   client_type TEXT NOT NULL CHECK (client_type IN ('individual', 'company')),
   product_type TEXT NOT NULL,
   region TEXT NOT NULL,
   profession INTEGER REFERENCES professions(id),
   profession_details TEXT,
   profession_classification TEXT,
   CONSTRAINT applications_custom_profession_check CHECK (
      (client_type = 'individual' AND profession = 17
         AND profession_details IS NOT NULL
         AND char_length(btrim(profession_details)) BETWEEN 2 AND 200
         AND profession_details = btrim(profession_details)
         AND profession_details !~ '[[:cntrl:]]'
         AND profession_classification IS NOT NULL
         AND profession_classification IN ('yes', 'no', 'unsure'))
      OR ((profession IS NULL OR profession <> 17)
         AND profession_details IS NULL AND profession_classification IS NULL)
   ),
   workplace TEXT,
   income NUMERIC CHECK (income >= 0),
   company_industry INTEGER REFERENCES company_industries(id),
   company_industry_details TEXT,
   company_industry_classification TEXT,
   CONSTRAINT applications_custom_industry_check CHECK (
      (client_type = 'company' AND company_industry = 7
         AND company_industry_details IS NOT NULL
         AND char_length(btrim(company_industry_details)) BETWEEN 2 AND 200
         AND company_industry_details = btrim(company_industry_details)
         AND company_industry_details !~ '[[:cntrl:]]'
         AND company_industry_classification IS NOT NULL
         AND company_industry_classification IN ('yes', 'no', 'unsure'))
      OR ((company_industry IS NULL OR company_industry <> 7)
         AND company_industry_details IS NULL AND company_industry_classification IS NULL)
   ),
   company_size TEXT,
   company_revenue NUMERIC CHECK (company_revenue >= 0),
   loan_amount NUMERIC NOT NULL CHECK (loan_amount > 0),
   loan_term INTEGER NOT NULL CHECK (loan_term > 0),
   purpose TEXT NOT NULL,
   purpose_details TEXT,
   CONSTRAINT applications_purpose_details_check CHECK (
      (purpose = 'other' AND purpose_details IS NOT NULL
         AND char_length(btrim(purpose_details)) BETWEEN 3 AND 200
         AND purpose_details = btrim(purpose_details)
         AND purpose_details !~ '[[:cntrl:]]')
      OR (purpose <> 'other' AND purpose_details IS NULL)
   ),
   created_at DATE NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Europe/Moscow')::date),
   CHECK (
      (client_type = 'individual' AND profession IS NOT NULL AND workplace IS NOT NULL
         AND income IS NOT NULL AND company_industry IS NULL AND company_size IS NULL AND company_revenue IS NULL)
      OR
      (client_type = 'company' AND company_industry IS NOT NULL AND company_size IS NOT NULL
         AND company_revenue IS NOT NULL AND profession IS NULL AND workplace IS NULL AND income IS NULL)
   )
);

CREATE INDEX applications_date_idx ON applications (created_at);
CREATE INDEX applications_region_idx ON applications (region);
CREATE INDEX applications_profession_idx ON applications (profession);
CREATE INDEX applications_industry_idx ON applications (company_industry);

COMMIT;
